export interface EligoOpcioj {
  /** The commit of the Fundamento checkout the run comes from (report „Eingabe“). */
  commit?: string;
}

function skribi(dosiero: string, enhavo: string | Uint8Array): void {
  mkdirSync(dirname(dosiero), { recursive: true });
  writeFileSync(dosiero, enhavo);
}

const unuigi = (vojo: string): string => vojo.split("\\").join("/");

/**
 * The seam that writes the run folder (`EkranojDeps.eligo`). One instance per run: it keeps the
 * input, the brand references and which photos were taken.
 */
export function eligoDe(opcioj: EligoOpcioj = {}): EkranojEligo {
  let out = "";
  let enigo: EkranojEnigo | undefined;
  let varianto: Varianto = "F";
  let lingvo = "de";
  let bildigilo = false;
  let marko: KadraMarko | undefined;
  const notoj: string[] = [];
  const bildoj = new Set<string>();

  const dokumentoDe = (slug: string, fragmento: string, plano: Plano, radiko: string): string => {
    const ekrano = plano.ekranoj.find((ero) => ero.slug === slug);
    return ekranaDokumento({
      titolo: ekrano?.titolo ?? slug,
      fragmento,
      varianto,
      lingvo,
      aspekto: enigo?.marko ?? "",
      marko,
      radiko,
    });
  };

  const skribiRondon = (n: number, stato: Rondo, plano: Plano): void => {
    for (const ekrano of plano.ekranoj) {
      const ero = stato[ekrano.slug];
      if (ero?.fragmento === undefined) continue;
      skribi(
        join(out, "rondoj", String(n), `${ekrano.slug}.html`),
        dokumentoDe(ekrano.slug, ero.fragmento, plano, "../../"),
      );
      if (ero.fakto !== undefined) {
        skribi(join(out, "rondoj", String(n), `${ekrano.slug}.fakto.json`), stabilaJson(ero.fakto));
      }
    }
  };

  return {
    komenco(e) {
      out = e.enigo.out;
      enigo = e.enigo;
      varianto = e.varianto;
      lingvo = e.lingvo;
      bildigilo = e.bildigilo;
      for (const ujo of ["ekranoj", "bildoj", "rondoj"]) {
        mkdirSync(join(out, ujo), { recursive: true });
      }
      if (e.marko === undefined) return;
      const markoDir = join(out, "marko");
      const rel = (vojo: string) => unuigi(isAbsolute(vojo) ? relative(markoDir, vojo) : vojo);
      let skripto: string | undefined;
      if (e.marko.skripto !== undefined) {
        const klasika = klasikaSkripto(readFileSync(join(markoDir, rel(e.marko.skripto)), "utf8"));
        if (klasika === undefined) {
          notoj.push(
            `Das Eroj-Bündel ${rel(e.marko.skripto)} ist nicht eigenständig (Importe); die Screens laden es als Modul und zeigen die Eroj nur über einen Server, nicht über file://.`,
          );
        } else {
          skribi(join(markoDir, KLASIKA_SKRIPTO), klasika);
          skripto = KLASIKA_SKRIPTO;
        }
      }
      marko = { css: e.marko.css.map(rel), ...(skripto === undefined ? {} : { skripto }) };
    },

    dokumento(e) {
      const html = dokumentoDe(
        e.ekrano.slug,
        e.fragmento,
        { celo: "", ekranoj: [e.ekrano], kantoj: [] },
        "../../",
      );
      const dosiero = join(out, "rondoj", String(e.rondo), `${e.ekrano.slug}.html`);
      skribi(dosiero, html);
      return { slug: e.ekrano.slug, html, dosiero };
    },

    bildigita(e) {
      skribi(join(out, "bildoj", `${e.slug}-hela.png`), e.bildigo.bildoj.hela);
      skribi(join(out, "bildoj", `${e.slug}-malhela.png`), e.bildigo.bildoj.malhela);
      bildoj.add(e.slug);
    },

    rondo(e) {
      skribiRondon(e.rondo, e.stato, e.plano);
    },

    fino(rezulto) {
      if (out === "") out = rezulto.dir;
      const { plano } = rezulto;
      rezulto.rondoj.forEach((stato, index) => {
        skribiRondon(index + 1, stato, plano);
      });
      const finaj = finajStatoj(rezulto);
      for (const [slug, stato] of finaj) {
        skribi(
          join(out, "ekranoj", `${slug}.html`),
          dokumentoDe(slug, stato.fragmento ?? "", plano, "../"),
        );
      }
      const bildaj = plano.ekranoj.map((ekrano) => ekrano.slug).filter((slug) => bildoj.has(slug));
      const raporto = raportoDe({
        id: basename(out),
        enigo: enigo ?? {
          frazo: plano.celo,
          marko: "",
          out,
          maksTokenoj: 0,
        },
        varianto,
        lingvo,
        ...(opcioj.commit === undefined ? {} : { commit: opcioj.commit }),
        bildigilo,
        rezulto,
        bildoj: bildaj,
        notoj,
      });
      skribi(join(out, "plano.json"), stabilaJson(plano));
      skribi(join(out, "mankoj.json"), stabilaJson(rezulto.mankoj));
      skribi(join(out, "raporto.json"), stabilaJson(raporto));
      skribi(join(out, "raporto.md"), raportoMarkdown(raporto));
      skribi(
        join(out, "superrigardo.html"),
        superrigardoHtml({
          plano,
          aspekto: enigo?.marko ?? "",
          lingvo,
          varianto,
          marko,
          ekranoj: plano.ekranoj.map((e) => e.slug).filter((slug) => finaj.has(slug)),
          bildoj: bildaj,
          verdaj: Object.fromEntries([...finaj].map(([slug, stato]) => [slug, stato.verda])),
        }),
      );
    },
  };
}
