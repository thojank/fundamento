// --- JSON ---------------------------------------------------------------------------------------

function ordigi(valoro: unknown): unknown {
  if (Array.isArray(valoro)) return valoro.map(ordigi);
  if (typeof valoro === "object" && valoro !== null) {
    const ordigita: Record<string, unknown> = {};
    for (const sxlosilo of Object.keys(valoro).sort()) {
      ordigita[sxlosilo] = ordigi((valoro as Record<string, unknown>)[sxlosilo]);
    }
    return ordigita;
  }
  return valoro;
}

/** JSON with sorted keys at every level, two-space indent, a final newline. */
export function stabilaJson(valoro: unknown): string {
  return `${JSON.stringify(ordigi(valoro), null, 2)}\n`;
}

