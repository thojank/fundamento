// The output folder of a run (Spec 037, S037-04, implementation spec §2.4, Lieferliste 1.6, 1.9):
//
//   plano.json · superrigardo.html · raporto.md · raporto.json · mankoj.json
//   ekranoj/<slug>.html              final screens (frame + last fragment)
//   marko/                           brand build (injected `Marko`) + the Eroj as a classic script
//   bildoj/<slug>-hela.png, -malhela.png
//   rondoj/<n>/<slug>.html           state of every round (D-26: carried rounds included)
//   rondoj/<n>/<slug>.fakto.json     the facts each round was scored on (D-33)
//
// `eligoDe` is the `EkranojEligo` seam of `kuruEkranojn`: it writes as the run goes (documents
// before their render, photos, rounds) and everything once more at the end from the result, so a
// partial run leaves a complete folder too. The report data and texts are pure functions.
// Deterministic: sorted keys, no timestamps; the run id (the folder name) carries the time, the
// duration is a number in the report.

