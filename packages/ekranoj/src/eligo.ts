/** The navigation of a flow in one round, from its screens (formula D-28, as `navigado`). */
export function fluaNavigado(plano: Plano, rondo: Rondo): FluaNavigado {
  const viditaj = new Set<string>();
  const planitaj: Kanto[] = [];
  for (const kanto of plano.kantoj) {
    const sxlosilo = `${kanto.de}\u0000${kanto.al}`;
    if (viditaj.has(sxlosilo)) continue;
    viditaj.add(sxlosilo);
    planitaj.push({ de: kanto.de, al: kanto.al });
  }
  const mankantajKantoj = planitaj.filter((kanto) => {
    const stato = rondo[kanto.de];
    return stato === undefined || stato.navigado.mankantaj.includes(kanto.al);
  });
  const mortajLigiloj = plano.ekranoj.flatMap(({ slug }) =>
    (rondo[slug]?.navigado.mortaj ?? []).map((href) => ({ de: slug, href })),
  );
  const kvoto =
    planitaj.length === 0
      ? mortajLigiloj.length === 0
        ? 1
        : 0
      : Math.max(0, planitaj.length - mankantajKantoj.length - mortajLigiloj.length) /
        planitaj.length;
  return { kvoto, mankantajKantoj, mortajLigiloj };
}

function axeDe(fakto: Fakto | undefined, scheme: "light" | "dark"): AxeStato {
  const renders = (fakto?.renders ?? []).filter((render) => render.scheme === scheme);
  return renders.length === 0 ? null : renders.flatMap((render) => render.axe);
}

function raportoEkranoDe(stato: RondoEkrano): RaportoEkrano {
  return {
    k: stato.taksado.k,
    total: stato.taksado.total,
    mankoj: stato.taksado.mankoj,
    k7: { bytes: stato.fakto?.bytes ?? null },
    malobservoj: stato.malobservoj,
    axe: { hela: axeDe(stato.fakto, "light"), malhela: axeDe(stato.fakto, "dark") },
    navigado: stato.navigado,
    verda: stato.verda,
    ...(stato.verdaEkde === undefined ? {} : { verdaEkde: stato.verdaEkde }),
    malhelpoj: stato.malhelpoj ?? [],
  };
}

/** The last state of every screen that was built: its round and its state. */
export function finajStatoj(rezulto: EkranojRezulto): Map<string, RondoEkrano> {
  const finaj = new Map<string, RondoEkrano>();
  for (const ekrano of rezulto.plano.ekranoj) {
    for (let i = rezulto.rondoj.length - 1; i >= 0; i -= 1) {
      const stato = rezulto.rondoj[i]?.[ekrano.slug];
      if (stato?.fragmento !== undefined) {
        finaj.set(ekrano.slug, stato);
        break;
      }
    }
  }
  return finaj;
}

function haltigoTekstoDe(rezulto: EkranojRezulto, cxiujVerdaj: boolean): string {
  const faritaj = rezulto.faritajRondoj ?? 0;
  switch (rezulto.haltigo) {
    case "max-tokens":
      return `Tokengrenze erreicht (--max-tokens) nach ${faritaj} von ${MAKS_RONDOJ} Runden; Teilergebnis.`;
    case "tagolimo":
      return `Tageslimit des Anbieters erreicht nach ${faritaj} von ${MAKS_RONDOJ} Runden; Teilergebnis.`;
    case "eraro":
      return `Abbruch durch einen Fehler nach ${faritaj} von ${MAKS_RONDOJ} Runden; Teilergebnis.`;
    default:
      if (faritaj === 0) return "Kein Screen gebaut.";
      return cxiujVerdaj
        ? `Alle Screens grün nach Runde ${faritaj}.`
        : `Höchstzahl von ${MAKS_RONDOJ} Runden erreicht, nicht alle Screens grün.`;
  }
}

/** The data of `raporto.json` (pure). */
export function raportoDe(e: RaportoEnigo): RaportoJson {
  const { rezulto } = e;
  const finaj = finajStatoj(rezulto);
  const bildoj = new Set(e.bildoj);
  const ekranoj: RaportoListero[] = rezulto.plano.ekranoj.map((ekrano) => {
    const stato = finaj.get(ekrano.slug);
    return {
      slug: ekrano.slug,
      titolo: ekrano.titolo,
      celo: ekrano.celo,
      ...(stato === undefined ? {} : { dosiero: `ekranoj/${ekrano.slug}.html` }),
      verda: stato?.verda === true,
      ...(stato?.verdaEkde === undefined ? {} : { verdaEkde: stato.verdaEkde }),
      ...(bildoj.has(ekrano.slug)
        ? {
            bildoj: {
              hela: `bildoj/${ekrano.slug}-hela.png`,
              malhela: `bildoj/${ekrano.slug}-malhela.png`,
            },
          }
        : {}),
    };
  });
  const elementoj = new Map<string, { nombro: number; ekranoj: string[] }>();
  for (const [slug, stato] of finaj) {
    for (const element of stato.fakto?.elements ?? []) {
      if (!element.tag.startsWith("fm-")) continue;
      const ero = elementoj.get(element.tag) ?? { nombro: 0, ekranoj: [] };
      ero.nombro += 1;
      if (!ero.ekranoj.includes(slug)) ero.ekranoj.push(slug);
      elementoj.set(element.tag, ero);
    }
  }
  const faritaj = rezulto.faritajRondoj ?? rezulto.rondoj.length;
  const rondoj: RaportoRondo[] = rezulto.rondoj.map((rondo, index) => ({
    n: index + 1,
    farita: index + 1 <= faritaj,
    navigado: fluaNavigado(rezulto.plano, rondo),
    ekranoj: Object.fromEntries(
      rezulto.plano.ekranoj.flatMap(({ slug }) => {
        const stato = rondo[slug];
        return stato === undefined ? [] : [[slug, raportoEkranoDe(stato)]];
      }),
    ),
  }));
  const cxiujVerdaj =
    ekranoj.length > 0 && ekranoj.every((ekrano) => ekrano.verda && ekrano.dosiero !== undefined);
  return {
    id: e.id,
    enigo: {
      frazo: e.enigo.frazo,
      marko: e.enigo.marko,
      varianto: e.varianto,
      lingvo: e.lingvo,
      maksTokenoj: e.enigo.maksTokenoj,
      ...(e.commit === undefined ? {} : { commit: e.commit }),
      ...(e.enigo.ekranoj === undefined ? {} : { ekranoj: e.enigo.ekranoj }),
    },
    bildigilo: e.bildigilo,
    plano: rezulto.plano,
    ekranoj,
    elementoj: [...elementoj.entries()]
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([tag, ero]) => ({ tag, ...ero })),
    rondoj,
    restantaj: rezulto.restantaj,
    mankoj: rezulto.mankoj,
    peno: rezulto.peno,
    kosto: rezulto.kosto,
    haltigo: rezulto.haltigo ?? null,
    haltigoTeksto: haltigoTekstoDe(rezulto, cxiujVerdaj),
    faritajRondoj: faritaj,
    dauxroMs: rezulto.peno.ms,
    ...(rezulto.takso === undefined ? {} : { takso: rezulto.takso }),
    notoj: [...(rezulto.notoj ?? []), ...(e.notoj ?? [])],
  };
}

// --- Report text (raporto.md) -------------------------------------------------------------------

const cxelo = (teksto: string | number): string =>
  String(teksto).replace(/\r?\n/g, " ").replace(/\|/g, "\\|");

const vico = (cxeloj: readonly (string | number)[]): string =>
  `| ${cxeloj.map(cxelo).join(" | ")} |`;

const nombro = (valoro: number | null): string =>
  valoro === null ? "–" : String(Math.round(valoro * 1000) / 1000);

function axeCxelo(stato: AxeStato): string {
  if (stato === null) return "nicht geprüft";
  return String(stato.length);
}

function verdaCxelo(ekrano: RaportoEkrano, n: number): string {
  if (ekrano.verdaEkde !== undefined && ekrano.verdaEkde < n) {
    return `grün seit Runde ${ekrano.verdaEkde}`;
  }
  return ekrano.verda ? "ja" : "nein";
}

function navigadoCxelo(navigado: EkranaNavigado): string {
  if (navigado.kompleta) return "vollständig";
  const partoj = [
    ...(navigado.mankantaj.length === 0 ? [] : [`fehlt: ${navigado.mankantaj.join(", ")}`]),
    ...(navigado.mortaj.length === 0 ? [] : [`tot: ${navigado.mortaj.join(", ")}`]),
  ];
  return partoj.length === 0 ? "unvollständig" : partoj.join("; ");
}

const kantoj = (listo: readonly Kanto[]): string =>
  listo.length === 0 ? "keine" : listo.map((kanto) => `${kanto.de} → ${kanto.al}`).join(", ");

/** The report of a run as Markdown, every section of Lieferliste 1.6 (pure). */
export function raportoMarkdown(r: RaportoJson): string {
  const linioj: string[] = [KAPO_MD, `# Bericht ${r.id}`, ""];

  linioj.push("## Eingabe", "");
  linioj.push(`- Satz: ${r.enigo.frazo}`);
  linioj.push(`- Marke: ${r.enigo.marko}`);
  linioj.push(`- Commit: ${r.enigo.commit ?? "unbekannt"}`);
  linioj.push(`- Variante: ${r.enigo.varianto}`);
  linioj.push(`- Sprache: ${r.enigo.lingvo}`);
  if (r.enigo.ekranoj !== undefined)
    linioj.push(`- Genannte Screens: ${r.enigo.ekranoj.join(", ")}`);
  linioj.push(`- Tokengrenze: ${r.enigo.maksTokenoj}`);
  if (r.takso !== undefined) linioj.push(`- ${r.takso.satz}`);
  linioj.push("");

  linioj.push("## Screens", "");
  linioj.push(`Ziel des Ablaufs: ${r.plano.celo}`, "");
  linioj.push(vico(["#", "Screen", "Titel", "Zweck", "Datei", "Stand"]));
  linioj.push("|---|---|---|---|---|---|");
  r.ekranoj.forEach((ekrano, index) => {
    const stato =
      ekrano.dosiero === undefined
        ? "nicht gebaut"
        : ekrano.verda
          ? ekrano.verdaEkde === undefined
            ? "grün"
            : `grün seit Runde ${ekrano.verdaEkde}`
          : "nicht grün";
    linioj.push(
      vico([
        index + 1,
        ekrano.slug,
        ekrano.titolo,
        ekrano.celo,
        ekrano.dosiero === undefined ? "–" : `[${ekrano.dosiero}](${ekrano.dosiero})`,
        stato,
      ]),
    );
  });
  linioj.push("", `Übergänge (Plan): ${kantoj(r.plano.kantoj)}`, "");

  linioj.push("## Verwendete Eroj und Sxablonoj", "");
  if (r.elementoj.length === 0) {
    linioj.push("Keine Eroj oder Sxablonoj (fm-*) in den Screens.");
  } else {
    linioj.push(vico(["Element", "Anzahl", "Screens"]), "|---|---|---|");
    for (const ero of r.elementoj) linioj.push(vico([ero.tag, ero.nombro, ero.ekranoj.join(", ")]));
  }
  linioj.push("");

  linioj.push("## Ergebnis je Runde", "");
  linioj.push(
    "K1–K6 aus der Bewertung (– = gilt nicht), K7 als Bytes des Markups; check_usage als Fehler/Hinweise; axe (WCAG 2.2 A/AA) als Zahl der verletzten Regeln je Modus; Navigation nach D-05.",
    "",
  );
  for (const rondo of r.rondoj) {
    linioj.push(`### Runde ${rondo.n}`, "");
    if (!rondo.farita) {
      linioj.push(
        "Nicht neu gebaut: die Werte der grünen Screens sind fortgeschrieben (D-26).",
        "",
      );
    }
    linioj.push(
      vico([
        "Screen",
        ...KRITERIOJ,
        "Total",
        "K7 Bytes",
        "check_usage",
        "axe hell",
        "axe dunkel",
        "Navigation",
        "grün",
      ]),
      `|${"---|".repeat(KRITERIOJ.length + 8)}`,
    );
    const malobservoj: string[] = [];
    const axeTrovoj: string[] = [];
    for (const [slug, ekrano] of Object.entries(rondo.ekranoj)) {
      const eraroj = ekrano.malobservoj.filter((m) => m.severity === "error").length;
      const sugestoj = ekrano.malobservoj.length - eraroj;
      linioj.push(
        vico([
          slug,
          ...KRITERIOJ.map((k) => nombro(ekrano.k[k])),
          nombro(ekrano.total),
          ekrano.k7.bytes === null ? "–" : ekrano.k7.bytes,
          r.enigo.varianto === "0" ? "–" : `${eraroj} Fehler, ${sugestoj} Hinweise`,
          axeCxelo(ekrano.axe.hela),
          axeCxelo(ekrano.axe.malhela),
          navigadoCxelo(ekrano.navigado),
          verdaCxelo(ekrano, rondo.n),
        ]),
      );
      for (const m of ekrano.malobservoj) {
        malobservoj.push(
          `- ${slug}: ${m.rule} (${m.severity}) bei ${m.loko ?? m.path}: ${m.message}${m.regulo === undefined ? "" : ` – Regulo ${m.regulo.name}, Grund: ${m.regulo.kialo}`}`,
        );
      }
      for (const [modus, stato] of [
        ["hell", ekrano.axe.hela],
        ["dunkel", ekrano.axe.malhela],
      ] as const) {
        for (const trovo of stato ?? []) {
          axeTrovoj.push(`- ${slug} ${modus}: ${trovo.id} (${trovo.nodes} Knoten)`);
        }
      }
    }
    linioj.push("");
    const nav = rondo.navigado;
    linioj.push(
      `Navigation (D-05): Anteil ${nombro(nav.kvoto)} · fehlende Übergänge: ${kantoj(nav.mankantajKantoj)} · tote Verweise: ${nav.mortajLigiloj.length === 0 ? "keine" : nav.mortajLigiloj.map((l) => `${l.de} → ${l.href}`).join(", ")}`,
      "",
    );
    if (r.enigo.varianto === "F") {
      if (malobservoj.length === 0) linioj.push("check_usage: keine Verstöße.", "");
      else linioj.push("check_usage:", "", ...malobservoj, "");
    }
    if (axeTrovoj.length > 0) linioj.push("axe:", "", ...axeTrovoj, "");
  }

  linioj.push("## Verbleibende Abweichungen", "");
  if (r.restantaj.length === 0) {
    linioj.push("Keine.");
  } else {
    linioj.push(vico(["Screen", "Regel", "Ort", "Grund"]), "|---|---|---|---|");
    for (const a of r.restantaj) linioj.push(vico([a.ekrano, a.regulo, a.loko, a.kialo]));
  }
  linioj.push("");

  // Teil 3 (S037-06): the gaps of this run, the table of the Lückenliste (also in mankoj.json).
  linioj.push("## Lücken (Teil 3)", "", mankojMarkdown(r.mankoj).trimEnd(), "");

  linioj.push("## Aufwand und Kosten", "");
  linioj.push(`- Tokens ein: ${r.peno.inputTokens}`);
  linioj.push(`- Tokens aus: ${r.peno.outputTokens}`);
  linioj.push(`- Anfragen: ${r.peno.requests}`);
  linioj.push(`- Werkzeugaufrufe: ${r.peno.toolCalls}`);
  linioj.push(`- Bytes (Markup): ${r.peno.bytes}`);
  linioj.push(
    r.kosto.usd === undefined
      ? "- Kosten: Kosten unbekannt"
      : `- Kosten: ${r.kosto.usd.toFixed(6)} $`,
  );
  linioj.push(`- Dauer: ${r.dauxroMs} ms`, "");

  linioj.push("## Halt", "");
  linioj.push(`- Haltgrund: ${r.haltigoTeksto}`);
  linioj.push(`- Gebaute Runden: ${r.faritajRondoj} von ${MAKS_RONDOJ}`);
  const notoj = [...r.notoj, ...(r.bildigilo ? [] : [SEN_BILDIGILO_FRAZO])];
  if (notoj.length > 0) linioj.push("", "Hinweise:", "", ...notoj.map((noto) => `- ${noto}`));
  linioj.push("");
  return linioj.join("\n");
}

