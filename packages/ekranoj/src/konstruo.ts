// The screen document (Spec 037, S037-04, D-24, D-27, D-34): a frame around the agent fragment.
// The frame names the language, the brand and the colour scheme on the root
// (`<html lang data-fm-aspekto data-fm-color-scheme>`), loads the brand build from the run's
// `marko/` folder by relative paths, and adds one back-link to the overview, marked
// `data-ekranoj-kadro`, outside the fragment – so the facts, the navigation (D-05) and axe never
// count it. The fragment stands verbatim between two comment markers. No timestamp, nothing of a
// brand but its name: the same fragment in two brands differs only in `data-fm-aspekto` (AC-7).
//
// D-24 (screens opened via file://): Chromium refuses `<script type="module" src>` from file:// (no
// CORS for an opaque origin), but loads classic scripts and stylesheets. The brand build's
// self-contained Eroj bundle (the Make Kit's `element.js`, an ES module without imports that
// defines every Ero on load) is therefore written once per run as a classic script
// (`klasikaSkripto`, `marko/ekranoj-eroj.js`) and loaded with `<script src>` – instead of inlining
// the 1.4 MB bundle into every screen and round as the Vitrino does with its one file.
//
// Variante 0 (D-34): the agent writes a whole document; the frame injects only the back-link and
// brings no Fundamento CSS and no Eroj. Pure functions only; eligo.ts writes the files.

import type { Plano, Varianto } from "./tipoj.js";

/** The attribute that marks what the frame adds (excluded from facts, axe and D-05, D-27). */
export const KADRO_ATRIBUTO = "data-ekranoj-kadro";
/** The markers around the agent fragment in a screen document. */
export const FRAGMENTO_KOMENCO = "<!-- ekranoj:fragmento -->";
export const FRAGMENTO_FINO = "<!-- /ekranoj:fragmento -->";
/** The classic-script form of the brand's Eroj bundle, inside `marko/` (D-24). */
export const KLASIKA_SKRIPTO = "ekranoj-eroj.js";

const KAPO_HTML =
  "<!-- Generated by @fundamento/ekranoj (Spec 037): frame around the agent fragment. Do not edit. -->";
const KAPO_SUPERRIGARDO =
  "<!-- Generated by @fundamento/ekranoj (Spec 037): overview of one run. Do not edit. -->";
const KAPO_SKRIPTO =
  "/* Generated by @fundamento/ekranoj (Spec 037, D-24): the self-contained Eroj bundle of the brand build as a classic script, so screens opened via file:// define the Eroj. Do not edit. */";

/** The brand build as a screen loads it: paths relative to the run's `marko/` folder. */
export interface KadraMarko {
  css: readonly string[];
  /** The classic script (`KLASIKA_SKRIPTO`), absent when the build brought no bundle. */
  skripto?: string;
}

export interface KadroEnigo {
  titolo: string;
  /** The agent fragment (Variante 0: the agent's whole document). */
  fragmento: string;
  varianto: Varianto;
  lingvo: string;
  /** The brand (Aspekto) named on the root. */
  aspekto: string;
  /** The brand build; absent = none (Variante 0 never loads one). */
  marko?: KadraMarko | undefined;
  /** From the document's folder to the run folder: `../` for `ekranoj/`, `../../` for `rondoj/<n>/`. */
  radiko: string;
}

/** Text for HTML content and attribute values. */
export const sxirmi = (teksto: string): string =>
  teksto.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** A relative URL path: every segment percent-encoded where needed, slashes kept. */
const vojo = (teksto: string): string => teksto.split("/").map(encodeURIComponent).join("/");

const SUPERRIGARDO_TEKSTO: Record<string, string> = { de: "Zur Übersicht", en: "To the overview" };

/** The back-link of the frame (D-27). */
function reenLigilo(radiko: string, lingvo: string): string {
  const teksto = SUPERRIGARDO_TEKSTO[lingvo] ?? SUPERRIGARDO_TEKSTO.de ?? "";
  return `<p ${KADRO_ATRIBUTO}><a href="${radiko}superrigardo.html">${sxirmi(teksto)}</a></p>`;
}

/** The head lines that load the brand build from `<radiko>marko/`. */
function markaKapo(marko: KadraMarko | undefined, radiko: string): string[] {
  if (marko === undefined) return [];
  return [
    ...marko.css.map((css) => `<link rel="stylesheet" href="${radiko}marko/${vojo(css)}">`),
    ...(marko.skripto === undefined
      ? []
      : [`<script src="${radiko}marko/${vojo(marko.skripto)}"></script>`]),
  ];
}

/** A page around a body: root attributes, title, brand, back-link (when `radiko` is given). */
function pagxo(e: {
  lingvo: string;
  titolo: string;
  aspekto?: string;
  marko?: KadraMarko | undefined;
  radiko: string;
  kapo: string;
  korpo: string[];
}): string {
  const radikaj =
    e.aspekto === undefined
      ? ""
      : ` data-fm-aspekto="${sxirmi(e.aspekto)}" data-fm-color-scheme="light"`;
  return [
    "<!doctype html>",
    e.kapo,
    `<html lang="${sxirmi(e.lingvo)}"${radikaj}>`,
    "<head>",
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    `<title>${sxirmi(e.titolo)}</title>`,
    ...markaKapo(e.marko, e.radiko),
    "</head>",
    "<body>",
    ...e.korpo,
    "</body>",
    "</html>",
    "",
  ].join("\n");
}

const DOKUMENTO = /<html[\s>]/i;
const KORPO = /<body(?:\s[^>]*)?>/i;

/** The screen document of a fragment (D-24, D-27, D-34). */
export function ekranaDokumento(e: KadroEnigo): string {
  const reen = reenLigilo(e.radiko, e.lingvo);
  if (e.varianto === "0" && DOKUMENTO.test(e.fragmento)) {
    const korpo = KORPO.exec(e.fragmento);
    if (korpo !== null) {
      const fino = korpo.index + korpo[0].length;
      const linifino = e.fragmento.startsWith("\n", fino) ? fino + 1 : fino;
      return `${e.fragmento.slice(0, linifino)}${linifino === fino ? "\n" : ""}${reen}\n${e.fragmento.slice(linifino)}`;
    }
    // A document without <body>: the back-link before the closing </html>.
    return e.fragmento.replace(/<\/html>/i, (fino) => `${reen}\n${fino}`);
  }
  const fundamento = e.varianto === "F";
  return pagxo({
    lingvo: e.lingvo,
    titolo: e.titolo,
    ...(fundamento ? { aspekto: e.aspekto, marko: e.marko } : {}),
    radiko: e.radiko,
    kapo: KAPO_HTML,
    korpo: [reen, FRAGMENTO_KOMENCO, e.fragmento, FRAGMENTO_FINO],
  });
}

/** The agent fragment of a screen document; undefined for a Variante-0 document of the agent. */
export function fragmentoEl(html: string): string | undefined {
  const komenco = html.indexOf(`${FRAGMENTO_KOMENCO}\n`);
  const fino = html.lastIndexOf(`\n${FRAGMENTO_FINO}`);
  if (komenco === -1 || fino === -1 || fino < komenco + FRAGMENTO_KOMENCO.length) return undefined;
  return html.slice(komenco + FRAGMENTO_KOMENCO.length + 1, fino);
}

/** What the agent wrote: the fragment, or the Variante-0 document without the frame's back-link. */
export function agentaTeksto(html: string): string {
  return (
    fragmentoEl(html) ??
    html.replace(new RegExp(`<p ${KADRO_ATRIBUTO}><a href="[^"]*">[^<]*</a></p>\\n`), "")
  );
}

const MODULA_FINO = /\n?export\s*\{[^}]*\};?\s*$/;

/**
 * The classic-script form of a self-contained ES module (D-24): its final `export { … }` dropped,
 * its body in a strict function scope (module code is strict; its names stay out of the page's
 * global scope). Undefined when the module is not self-contained (imports, `import.meta`, other
 * exports) – then the screens cannot define the Eroj under file://.
 */
export function klasikaSkripto(modulo: string): string | undefined {
  const korpo = modulo.replace(MODULA_FINO, "\n");
  if (/^\s*(?:import|export)\b/m.test(korpo) || /\bimport\s*\.\s*meta\b/.test(korpo)) {
    return undefined;
  }
  return `${KAPO_SKRIPTO}\n(() => {\n"use strict";\n${korpo.trimEnd()}\n})();\n`;
}

// --- The overview (AC-6) ------------------------------------------------------------------------

export interface SuperrigardoEnigo {
  plano: Plano;
  aspekto: string;
  lingvo: string;
  varianto: Varianto;
  marko?: KadraMarko | undefined;
  /** Slugs with a screen file in `ekranoj/`. */
  ekranoj: readonly string[];
  /** Slugs with photos in `bildoj/`. */
  bildoj: readonly string[];
  /** Green per slug at the end of the run. */
  verdaj: Readonly<Record<string, boolean>>;
}

const SUPERRIGARDO_TEKSTOJ = {
  de: {
    titolo: "Übersicht",
    raporto: "Bericht",
    verda: "grün",
    neVerda: "nicht grün",
    neKonstruita: "nicht gebaut",
    foto: "Bildschirmfoto",
  },
  en: {
    titolo: "Overview",
    raporto: "Report",
    verda: "green",
    neVerda: "not green",
    neKonstruita: "not built",
    foto: "Screenshot",
  },
} as const;

/**
 * The overview of a run: a tile per planned screen with title, purpose, state and photo, links to
 * every built screen and to the report; the same brand build as the screens (Variante F).
 */
export function superrigardoHtml(e: SuperrigardoEnigo): string {
  const t = e.lingvo === "en" ? SUPERRIGARDO_TEKSTOJ.en : SUPERRIGARDO_TEKSTOJ.de;
  const konstruitaj = new Set(e.ekranoj);
  const bildoj = new Set(e.bildoj);
  const kaheloj = e.plano.ekranoj.flatMap((ekrano) => {
    const konstruita = konstruitaj.has(ekrano.slug);
    const stato = !konstruita ? t.neKonstruita : e.verdaj[ekrano.slug] ? t.verda : t.neVerda;
    const titolo = konstruita
      ? `<h2><a href="ekranoj/${vojo(ekrano.slug)}.html">${sxirmi(ekrano.titolo)}</a></h2>`
      : `<h2>${sxirmi(ekrano.titolo)}</h2>`;
    return [
      "<li>",
      "<article>",
      titolo,
      `<p>${sxirmi(ekrano.celo)}</p>`,
      `<p>${sxirmi(stato)}</p>`,
      ...(bildoj.has(ekrano.slug)
        ? [
            `<img src="bildoj/${vojo(ekrano.slug)}-hela.png" alt="${sxirmi(`${t.foto}: ${ekrano.titolo}`)}">`,
          ]
        : []),
      "</article>",
      "</li>",
    ];
  });
  const fundamento = e.varianto === "F";
  return pagxo({
    lingvo: e.lingvo,
    titolo: `${t.titolo}: ${e.plano.celo}`,
    ...(fundamento ? { aspekto: e.aspekto, marko: e.marko } : {}),
    radiko: "",
    kapo: KAPO_SUPERRIGARDO,
    korpo: [
      "<main>",
      `<h1>${sxirmi(e.plano.celo)}</h1>`,
      `<p><a href="raporto.md">${sxirmi(t.raporto)}</a></p>`,
      "<ul>",
      ...kaheloj,
      "</ul>",
      "</main>",
    ],
  });
}
